// Единый гард UUID для параметров маршрутов и тел запросов.
//
// PostgreSQL выбрасывает 22P02 (invalid input syntax for type uuid) на
// произвольных строках в запросах к uuid-колонкам — невалидные значения
// должны отсекаться до обращения к БД и давать чистый 400/404.
// Инцидент 2026-09-22: reviews/product/:id ронял процесс на невалидном
// значении; класс повторился в orders/users/products — отсюда общий утиль.
//
// Версия UUID намеренно не проверяется: схема использует gen_random_uuid()
// (v4), но гард пропускает любой синтаксически валидный UUID, чтобы не
// ломаться на исторических/импортированных id.
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

function isUuid(value) {
  return typeof value === "string" && UUID_RE.test(value);
}

module.exports = { isUuid, UUID_RE };
