-- ADR 007, поправка 2026-09-23: транслит-слаги товаров удалены как
-- оверинжиниринг. URL товара — непрозрачный идентификатор (UUID), как и
-- категории (/category/:id). Откатывает часть миграции 002, которая не ушла
-- в прод (миграции 001/002 применены только в локальных dev-БД):
--   1. столбец products.slug вместе с индексом idx_products_slug;
--   2. section 2 (индексы pg_trgm / сортировки) и section 3 (content_pages)
--      остаются нетронутыми — они не связаны со слагами.
-- Идемпотентна (IF EXISTS везде) и безопасна к повторному применению.

DROP INDEX IF EXISTS idx_products_slug;
ALTER TABLE products DROP COLUMN IF EXISTS slug;
